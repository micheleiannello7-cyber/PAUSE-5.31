export const dictionaries = { it, en };
export type Dict = typeof it;

type Ctx = { lang: Lang; t: Dict; setLang: (l: Lang) => void; ready: boolean };
const I18nContext = createContext<Ctx>({ lang: "it", t: it, setLang: () => {}, ready: false });

function deviceLang(): Lang {
  const code = getLocales()[0]?.languageCode ?? "it";
  return code === "en" ? "en" : "it";
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("it");
  const [ready, setReady] = useState(false);

  useEffect(() => {
    let cancelled = false;
    const apply = (l: Lang) => {
      if (cancelled) return;
      setApiLang(l);
      setLangState(l);
      setReady(true);
    };
    const fallback = () => apply(deviceLang());
    // Never hang on a blocked storage backend — fall back to the device language.
    const timer = setTimeout(fallback, 2000);
    AsyncStorage.getItem(LANG_KEY)
      .then((stored) => {
        clearTimeout(timer);
        apply(stored === "en" || stored === "it" ? stored : deviceLang());
      })
      .catch(() => {
        clearTimeout(timer);
        fallback();
      });
    return () => {
      cancelled = true;
      clearTimeout(timer);
    };
  }, []);

  const setLang = (l: Lang) => {
    setApiLang(l);
    setLangState(l);
    AsyncStorage.setItem(LANG_KEY, l);
    // Content is language-dependent: refetch everything.
    queryClient.invalidateQueries();
  };

  const value = useMemo(() => ({ lang, t: dictionaries[lang], setLang, ready }), [lang, ready]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
